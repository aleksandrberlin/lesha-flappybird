const FONT_BITS = {};
for (const ch in FONT_GLYPHS) FONT_BITS[ch] = FONT_GLYPHS[ch].split(",");

function textWidth(str, scale) {
  return str.length ? (str.length * (FONT_W + 1) - 1) * scale : 0;
}

// align: "left" | "center" | "right"
function drawText(ctx, str, x, y, opts) {
  const o = opts || {};
  const scale = o.scale || 1;
  const color = o.color || "#ffffff";
  const text = String(str).toUpperCase();
  let px = x;
  if (o.align === "center") px = Math.round(x - textWidth(text, scale) / 2);
  else if (o.align === "right") px = Math.round(x - textWidth(text, scale));
  const py = Math.round(y);

  if (o.shadow) {
    drawText(ctx, text, px + scale, py + scale,
      Object.assign({}, o, { align: "left", color: o.shadow, shadow: null, outline: null }));
  }
  if (o.outline) {
    const s = scale;
    for (const [dx, dy] of [[-s, 0], [s, 0], [0, -s], [0, s]]) {
      drawText(ctx, text, px + dx, py + dy,
        Object.assign({}, o, { align: "left", color: o.outline, shadow: null, outline: null }));
    }
  }

  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const bits = FONT_BITS[text[i]];
    if (!bits) continue;
    const gx = px + i * (FONT_W + 1) * scale;
    for (let row = 0; row < FONT_H; row++) {
      const line = bits[row];
      for (let col = 0; col < FONT_W; col++) {
        if (line[col] === "1") ctx.fillRect(gx + col * scale, py + row * scale, scale, scale);
      }
    }
  }
}
